"""Locked component headers must match their declared checksums when present.

`managed_components/` is generated by ESP-IDF from `dependencies.lock` and is
not committed, so a clean checkout (including CI test jobs) legitimately has
no such directory. When components are available, verify the vendored header
still matches the lock; otherwise skip instead of failing a source-only job.
"""

import hashlib
import json
from pathlib import Path
import unittest


class FirmwareDependencyTests(unittest.TestCase):
    def test_zlib_config_header_matches_the_locked_component(self):
        component = Path(__file__).resolve().parents[2] / "managed_components/espressif__zlib"
        checksums = component / "CHECKSUMS.json"
        if not checksums.is_file():
            self.skipTest("managed_components not restored (generated by ESP-IDF)")
        manifest = json.loads(checksums.read_text(encoding="utf-8"))
        expected = next(item for item in manifest["files"] if item["path"] == "zlib/zconf.h")
        header = (component / expected["path"]).read_bytes()
        self.assertEqual(len(header), expected["size"])
        self.assertEqual(hashlib.sha256(header).hexdigest(), expected["hash"])


if __name__ == "__main__":
    unittest.main()
