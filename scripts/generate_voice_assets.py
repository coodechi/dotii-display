#!/usr/bin/env python3
"""Generate Chinese voice prompts as C arrays for the ESP32 firmware.

Requires macOS `say` (Tingting voice) and `afconvert`. Output is 16 kHz,
16-bit signed LE, mono raw PCM compiled into the firmware.

Usage: python3 scripts/generate_voice_assets.py
"""
from __future__ import annotations

import pathlib
import subprocess
import tempfile
import wave

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUT_DIR = ROOT / "main" / "generated"
VOICE = "Tingting"
SAMPLE_RATE = 16000

# Hour spoken forms: "零点整" ... "二十三点整".
HOURS = [
    "零点整", "一点整", "两点整", "三点整", "四点整", "五点整",
    "六点整", "七点整", "八点整", "九点整", "十点整", "十一点整",
    "十二点整", "十三点整", "十四点整", "十五点整", "十六点整",
    "十七点整", "十八点整", "十九点整", "二十点整", "二十一点整",
    "二十二点整", "二十三点整",
]
PHRASES = {"print_done": "打印完成"}


def synth(text: str, work: pathlib.Path) -> bytes:
    aiff = work / "voice.aiff"
    wav = work / "voice.wav"
    subprocess.run(["say", "-v", VOICE, "-o", str(aiff), text], check=True)
    subprocess.run(
        ["afconvert", "-f", "WAVE", "-d", f"LEI16@{SAMPLE_RATE}", str(aiff), str(wav)],
        check=True,
    )
    with wave.open(str(wav), "rb") as w:
        assert w.getnchannels() == 1
        assert w.getsampwidth() == 2
        assert w.getframerate() == SAMPLE_RATE
        return w.readframes(w.getnframes())


def c_array(name: str, data: bytes) -> str:
    values = []
    for i in range(0, len(data), 2):
        sample = int.from_bytes(data[i:i + 2], "little", signed=True)
        values.append(str(sample))
    lines = []
    for i in range(0, len(values), 20):
        lines.append("    " + ", ".join(values[i:i + 20]) + ",")
    return f"const int16_t {name}[] = {{\n" + "\n".join(lines) + "\n};\n"


def main() -> None:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    header = ["/** Auto-generated by scripts/generate_voice_assets.py. Do not edit. */",
              "#pragma once", "", "#include <stdint.h>", ""]
    source = ["/** Auto-generated by scripts/generate_voice_assets.py. Do not edit. */",
              '#include "voice_assets.h"', ""]

    entries: list[tuple[str, bytes]] = []
    with tempfile.TemporaryDirectory() as tmp:
        work = pathlib.Path(tmp)
        for hour, text in enumerate(HOURS):
            data = synth(text, work)
            name = f"voice_hour_{hour:02d}"
            entries.append((name, data))
            header.append(f"extern const int16_t {name}[];")
            header.append(f"#define {name.upper()}_LEN {len(data) // 2}")
            print(f"hour {hour:02d} {text}: {len(data) // 2} samples")
        for key, text in PHRASES.items():
            data = synth(text, work)
            name = f"voice_{key}"
            entries.append((name, data))
            header.append(f"extern const int16_t {name}[];")
            header.append(f"#define {name.upper()}_LEN {len(data) // 2}")
            print(f"{key} {text}: {len(data) // 2} samples")

    header.append("")
    source.append("/* Hour voice prompts, 16 kHz / s16le / mono. */")
    for name, data in entries:
        source.append(c_array(name, data))

    (OUT_DIR / "voice_assets.h").write_text("\n".join(header), encoding="utf-8")
    (OUT_DIR / "voice_assets.c").write_text("\n".join(source), encoding="utf-8")
    total = sum(len(d) for _, d in entries)
    print(f"Wrote {len(entries)} prompts, {total} bytes PCM to {OUT_DIR}")


if __name__ == "__main__":
    main()
